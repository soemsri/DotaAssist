export class NeutralAdvisorEngine {
  /**
   * Get recommendations for a specific tier and hero
   */
  public getRecommendations(
    heroNameOrKey: string,
    tier: number,
  ): NeutralItemRecommendation[] {
    const validTier = Math.max(1, Math.min(5, tier || 1));
    const { archetype } = getHeroArchetype(heroNameOrKey);
    const tierData = NEUTRAL_TIER_DATABASE[validTier];

    if (!tierData || !tierData[archetype]) {
      return NEUTRAL_TIER_DATABASE[1].PhysicalCarryMelee;
    }

    return tierData[archetype];
  }

  /**
   * Get all 5 tiers of recommendations for a hero
   */
  public getAllTierRecommendations(
    heroNameOrKey: string,
  ): Record<number, NeutralItemRecommendation[]> {
    const { archetype } = getHeroArchetype(heroNameOrKey);
    const result: Record<number, NeutralItemRecommendation[]> = {};

    for (let t = 1; t <= 5; t++) {
      result[t] = NEUTRAL_TIER_DATABASE[t][archetype];
    }

    return result;
  }
}

export const neutralAdvisor = new NeutralAdvisorEngine();
