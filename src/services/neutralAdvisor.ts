/**
 * Categorize a hero into one of the 6 archetypes for neutral item matching
 */
export function getHeroArchetype(heroNameOrKey: string): {
  archetype: HeroArchetype;
  displayName: string;
  roleLabelTh: string;
  roleLabelEn: string;
} {
  const clean = heroNameOrKey.replace(/^npc_dota_hero_/, "").toLowerCase();
  const hero = HEROES_BY_NAME.get(clean);

  if (ARCHETYPE_OVERRIDES[clean]) {
    const arch = ARCHETYPE_OVERRIDES[clean];
    return {
      archetype: arch,
      displayName: hero?.localized_name || clean.replace(/_/g, " "),
      ...getRoleLabels(arch),
    };
  }

  if (hero) {
    const isRanged = hero.attack_type === "Ranged";
    const isUniversal = hero.primary_attr === "all";
    const hasCarryRole = hero.roles.includes("Carry");
    const hasSupportRole = hero.roles.includes("Support");
    const hasTankRole = hero.roles.includes("Durable") || hero.roles.includes("Initiator");

    let arch: HeroArchetype;
    if (isUniversal) {
      arch = "UniversalAllRounder";
    } else if (hasCarryRole && !hasSupportRole) {
      arch = isRanged ? "PhysicalCarryRanged" : "PhysicalCarryMelee";
    } else if (hero.primary_attr === "int" || hero.roles.includes("Nuker")) {
      arch = hasSupportRole ? "SupportUtility" : "SpellCaster";
    } else if (hasTankRole || hero.primary_attr === "str") {
      arch = "TankInitiator";
    } else if (hasSupportRole) {
      arch = "SupportUtility";
    } else {
      arch = isRanged ? "PhysicalCarryRanged" : "PhysicalCarryMelee";
    }

    return {
      archetype: arch,
      displayName: hero.localized_name,
      ...getRoleLabels(arch),
    };
  }

  // Default fallback
  return {
    archetype: "PhysicalCarryMelee",
    displayName: clean ? clean.replace(/_/g, " ") : "Hero",
    roleLabelTh: "แครี่ / โจมตีประชิด",
    roleLabelEn: "Physical Carry (Melee)",
  };
}

/**
 * Determines if a hero is typically played as Support (Pos 4 / Pos 5)
 */
export function isSupportHero(heroNameOrKey: string): boolean {
  if (!heroNameOrKey) return false;
  const clean = heroNameOrKey.replace(/^npc_dota_hero_/, "").toLowerCase();
  const info = getHeroArchetype(clean);
  if (info.archetype === "SupportUtility") {
    return true;
  }
  const hero = HEROES_BY_NAME.get(clean);
  return Boolean(hero?.roles?.includes("Support"));
}

function getRoleLabels(arch: HeroArchetype) {
  switch (arch) {
    case "PhysicalCarryMelee":
      return { roleLabelTh: "แครี่ / โจมตีประชิด", roleLabelEn: "Physical Carry (Melee)" };
    case "PhysicalCarryRanged":
      return { roleLabelTh: "แครี่ / โจมตีระยะไกล", roleLabelEn: "Physical Carry (Ranged)" };
    case "SpellCaster":
      return { roleLabelTh: "เวท / นุ๊กเกอร์", roleLabelEn: "Spell Caster / Nuker" };
    case "TankInitiator":
      return { roleLabelTh: "แทงก์ / ตัวเปิดไฟต์", roleLabelEn: "Tank / Initiator" };
    case "SupportUtility":
      return { roleLabelTh: "ซัพพอร์ต / ยูทิลิตี้", roleLabelEn: "Support / Utility" };
    case "UniversalAllRounder":
      return { roleLabelTh: "ยูนิเวอร์แซล / รอบด้าน", roleLabelEn: "Universal / Flex" };
  }
}

